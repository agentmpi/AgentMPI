import json

translation = """CHAPITRE IX.
L'histoire de la Fausse-Tortue


« Vous ne pouvez pas imaginer combien je suis heureuse de vous revoir, ma
chère vieille amie ! » dit la Duchesse en glissant affectueusement son bras
sous celui d'Alice, et elles s'en allèrent ensemble.

Alice fut très contente de la trouver d'une humeur si agréable, et se dit à
part elle que c'était peut-être seulement le poivre qui l'avait rendue si
féroce lorsqu'elles s'étaient rencontrées dans la cuisine.

« Quand _je_ serai duchesse, » se dit-elle (d'un ton toutefois assez peu
confiant), « je ne veux pas de poivre _du tout_ dans ma cuisine. La soupe
s'en passe très bien — peut-être est-ce toujours le poivre qui rend les gens
colériques, » continua-t-elle, tout à fait ravie d'avoir découvert une
nouvelle sorte de règle, « et le vinaigre qui les rend aigres — et la
camomille qui les rend amers — et — et le sucre d'orge et les choses de ce
genre qui rendent les enfants d'humeur douce. Je voudrais bien que les gens
sachent _cela_ : alors ils ne seraient pas si avares là-dessus, vous
savez — »

Elle avait tout à fait oublié la Duchesse à ce moment-là, et fut un peu
saisie en entendant sa voix tout près de son oreille. « Vous pensez à
quelque chose, ma chère, et cela vous fait oublier de parler. Je ne puis pas
vous dire à l'instant quelle est la morale de ceci, mais je m'en souviendrai
dans un moment. »

« Peut-être n'en a-t-elle pas, » se hasarda à remarquer Alice.

« Ta, ta, ta, mon enfant ! » dit la Duchesse. « Tout a une morale, pourvu
qu'on sache la trouver. » Et elle se serra de plus près contre le côté
d'Alice tout en parlant.

Alice n'aimait pas beaucoup rester si près d'elle : d'abord parce que la
Duchesse était _très_ laide ; et ensuite parce qu'elle avait exactement la
taille qu'il fallait pour appuyer son menton sur l'épaule d'Alice, et
c'était un menton d'une pointe désagréablement aiguë. Cependant, elle ne
voulait pas être impolie, aussi le supporta-t-elle du mieux qu'elle put.

« La partie va un peu mieux maintenant, » dit-elle, histoire d'entretenir un
peu la conversation.

« C'est vrai, » dit la Duchesse : « et la morale de ceci est : “Oh ! c'est
l'amour, c'est l'amour qui fait tourner le monde !” »

« Quelqu'un a dit, » murmura Alice, « que cela se fait parce que chacun
s'occupe de ses propres affaires ! »

« Ah bon ! Cela veut dire à peu près la même chose, » dit la Duchesse, en
enfonçant son petit menton pointu dans l'épaule d'Alice tandis qu'elle
ajoutait : « et la morale de _ceci_ est : “Prenez soin du sens, et les sons
prendront soin d'eux-mêmes.” »

« Comme elle aime trouver des morales à toutes choses ! » pensa Alice à part
elle.

« J'imagine que vous vous demandez pourquoi je ne passe pas mon bras autour
de votre taille, » dit la Duchesse après une pause : « la raison en est que
j'ai des doutes sur l'humeur de votre flamant. Faut-il que je tente
l'expérience ? »

« Il pourrait mordre, » répondit prudemment Alice, qui n'avait pas du tout
envie de voir tenter l'expérience.

« Très juste, » dit la Duchesse : « les flamants et la moutarde mordent tous
les deux. Et la morale de ceci est : “Qui se ressemble s'assemble.” »

« Seulement la moutarde n'est pas un oiseau, » fit remarquer Alice.

« Juste, comme toujours, » dit la Duchesse : « quelle façon claire vous avez
de présenter les choses ! »

« C'est un minéral, je _crois_, » dit Alice.

« Bien sûr que c'en est un, » dit la Duchesse, qui semblait prête à tomber
d'accord sur tout ce que disait Alice ; « il y a une grande mine de moutarde
près d'ici. Et la morale de ceci est : “Plus il y a de mine, moins il y a de
tienne.” »

« Oh, je sais ! » s'exclama Alice, qui n'avait pas fait attention à cette
dernière remarque, « c'est un végétal. Cela n'en a pas l'air, mais c'en est
un. »

« Je suis tout à fait d'accord avec vous, » dit la Duchesse ; « et la morale
de ceci est : “Sois ce que tu voudrais paraître” — ou, si vous préférez que
ce soit dit plus simplement : “Ne t'imagine jamais ne pas être autrement que
ce qu'il pourrait sembler aux autres que ce que tu étais ou aurais pu être
n'était pas autrement que ce que tu avais été ne leur aurait pas semblé
être autrement.” »

« Je crois que je comprendrais mieux cela, » dit Alice très poliment, « si
je l'avais par écrit : mais je ne puis pas très bien le suivre comme vous le
dites. »

« Ce n'est rien auprès de ce que je pourrais dire si je le voulais, »
répliqua la Duchesse d'un ton satisfait.

« Je vous en prie, ne prenez pas la peine d'en dire plus long que cela, »
dit Alice.

« Oh, ne parlez pas de peine ! » dit la Duchesse. « Je vous fais cadeau de
tout ce que j'ai dit jusqu'ici. »

« Un cadeau à bon marché ! » pensa Alice. « Je suis bien contente qu'on ne
donne pas des cadeaux d'anniversaire comme celui-là ! » Mais elle n'osa pas
le dire tout haut.

« Encore en train de penser ? » demanda la Duchesse, avec un nouveau coup de
son petit menton pointu.

« J'ai bien le droit de penser, » dit Alice vivement, car elle commençait à
se sentir un peu inquiète.

« À peu près autant le droit, » dit la Duchesse, « que les cochons ont de
voler ; et la mo— »

Mais ici, au grand étonnement d'Alice, la voix de la Duchesse s'éteignit,
même au milieu de son mot favori, « morale », et le bras qui était passé
sous le sien commença à trembler. Alice leva les yeux, et là, devant elles,
se tenait la Reine, les bras croisés, le sourcil froncé comme un orage.

« Une belle journée, Votre Majesté ! » commença la Duchesse d'une voix basse
et faible.

« Maintenant, je vous avertis loyalement, » cria la Reine en frappant du
pied contre le sol tout en parlant ; « ou bien vous, ou bien votre tête,
doit s'en aller, et cela en moins de rien ! Choisissez ! »

La Duchesse fit son choix, et disparut en un instant.

« Continuons la partie, » dit la Reine à Alice ; et Alice était bien trop
effrayée pour dire un mot, mais elle la suivit lentement jusqu'au terrain de
croquet.

Les autres invités avaient profité de l'absence de la Reine et se reposaient
à l'ombre : cependant, dès qu'ils la virent, ils se hâtèrent de revenir au
jeu, la Reine se contentant de faire remarquer qu'un instant de retard leur
coûterait la vie.

Tout le temps qu'ils jouèrent, la Reine ne cessa pas de se quereller avec
les autres joueurs, et de crier « Qu'on lui coupe la tête, à lui ! » ou
« Qu'on lui coupe la tête, à elle ! » Ceux qu'elle condamnait étaient
emmenés sous bonne garde par les soldats, qui, naturellement, devaient
cesser d'être des arches pour faire cela, si bien qu'au bout d'une
demi-heure environ il ne restait plus une seule arche, et que tous les
joueurs, sauf le Roi, la Reine et Alice, étaient prisonniers et condamnés à
mort.

Alors la Reine s'arrêta, tout à fait hors d'haleine, et dit à Alice :
« Avez-vous déjà vu la Fausse-Tortue ? »

« Non, » dit Alice. « Je ne sais même pas ce qu'est une Fausse-Tortue. »

« C'est la chose avec laquelle on fait la soupe à la Fausse-Tortue, » dit la
Reine.

« Je n'en ai jamais vu, ni jamais entendu parler, » dit Alice.

« Venez donc, » dit la Reine, « et elle vous racontera son histoire. »

Tandis qu'elles s'en allaient ensemble, Alice entendit le Roi dire à voix
basse, à la compagnie en général : « Vous êtes tous pardonnés. » « Allons,
_voilà_ une bonne chose ! » se dit-elle, car elle s'était sentie tout à fait
malheureuse du nombre d'exécutions que la Reine avait ordonnées.

Elles arrivèrent bientôt auprès d'un Griffon, étendu et profondément endormi
au soleil. (Si vous ne savez pas ce qu'est un Griffon, regardez l'image.)
« Debout, paresseux ! » dit la Reine, « et conduisez cette jeune demoiselle
voir la Fausse-Tortue et entendre son histoire. Il faut que je retourne
surveiller quelques exécutions que j'ai ordonnées ; » et elle s'en alla,
laissant Alice seule avec le Griffon. Alice n'aimait pas beaucoup l'air de
cette créature, mais, à tout prendre, elle pensa qu'il serait tout aussi sûr
de rester avec lui que de suivre cette Reine féroce : elle attendit donc.

Le Griffon se dressa et se frotta les yeux : puis il regarda la Reine
jusqu'à ce qu'elle fût hors de vue : puis il pouffa de rire. « Quelle bonne
farce ! » dit le Griffon, moitié pour lui-même, moitié pour Alice.

« Quelle _est_ la farce ? » dit Alice.

« Mais _elle_, » dit le Griffon. « C'est tout dans son imagination, ça : on
n'exécute jamais personne, vous savez. Venez ! »

« Tout le monde dit “venez !” ici, » pensa Alice en le suivant lentement :
« on ne m'a jamais autant commandée de toute ma vie, jamais ! »

Ils n'étaient pas allés loin lorsqu'ils aperçurent la Fausse-Tortue dans le
lointain, assise, triste et solitaire, sur une petite corniche de rocher,
et, comme ils approchaient, Alice pouvait l'entendre soupirer comme si son
cœur allait se briser. Elle la prit profondément en pitié. « Quel est son
chagrin ? » demanda-t-elle au Griffon, et le Griffon répondit, presque dans
les mêmes termes qu'auparavant : « C'est tout dans son imagination, ça :
elle n'a pas de chagrin du tout, vous savez. Venez ! »

Ils s'approchèrent donc de la Fausse-Tortue, qui les regarda avec de grands
yeux pleins de larmes, mais ne dit rien.

« Cette jeune demoiselle ici présente, » dit le Griffon, « elle veut pour
savoir votre histoire, qu'elle veut. »

« Je vais la lui raconter, » dit la Fausse-Tortue d'un ton grave et creux :
« asseyez-vous tous les deux, et ne dites pas un mot avant que j'aie
fini. »

Ils s'assirent donc, et personne ne parla pendant quelques minutes. Alice se
dit à part elle : « Je ne vois pas comment elle pourra _jamais_ finir, si
elle ne commence pas. » Mais elle attendit patiemment.

« Autrefois, » dit enfin la Fausse-Tortue avec un profond soupir, « j'étais
une vraie Tortue. »

Ces mots furent suivis d'un très long silence, rompu seulement par une
exclamation occasionnelle de « Hjckrrh ! » de la part du Griffon, et par les
lourds sanglots continuels de la Fausse-Tortue. Alice fut bien près de se
lever et de dire : « Merci, madame, de votre intéressante histoire, » mais
elle ne pouvait s'empêcher de penser qu'il _devait_ y avoir encore quelque
chose à venir, aussi resta-t-elle assise sans rien dire.

« Quand nous étions petites, » reprit enfin la Fausse-Tortue, plus
calmement, quoique sanglotant encore un peu de temps à autre, « nous allions
à l'école dans la mer. La maîtresse était une vieille Tortue — nous
l'appelions Tortue grecque — »

« Pourquoi l'appeliez-vous Tortue grecque, si elle n'en était pas une ? »
demanda Alice.

« Nous l'appelions Tortue grecque parce qu'elle nous enseignait le grec, »
dit la Fausse-Tortue avec colère : « vraiment, vous êtes bien bornée ! »

« Vous devriez avoir honte de poser une question aussi simple, » ajouta le
Griffon ; et puis ils restèrent tous deux assis en silence, à regarder la
pauvre Alice, qui se sentait prête à s'enfoncer sous terre. Enfin le Griffon
dit à la Fausse-Tortue : « En avant, ma vieille ! N'y passez pas la
journée ! » et elle continua en ces termes :

« Oui, nous allions à l'école dans la mer, quoique vous ne le croyiez
peut-être pas — »

« Je n'ai jamais dit que je ne le croyais pas ! » interrompit Alice.

« Si, vous l'avez dit, » dit la Fausse-Tortue.

« Taisez-vous ! » ajouta le Griffon, avant qu'Alice pût parler de nouveau.
La Fausse-Tortue continua.

« Nous recevions la meilleure des éducations — en fait, nous allions à
l'école tous les jours — »

« _Moi aussi_, j'ai été dans une école de jour, » dit Alice ; « vous n'avez
pas besoin d'en être si fière que cela. »

« Avec des matières en supplément ? » demanda la Fausse-Tortue un peu
anxieusement.

« Oui, » dit Alice, « nous apprenions le français et la musique. »

« Et le blanchissage ? » dit la Fausse-Tortue.

« Certainement pas ! » dit Alice avec indignation.

« Ah ! alors la vôtre n'était pas une école vraiment bonne, » dit la
Fausse-Tortue d'un ton de grand soulagement. « Chez _nous_, on avait au bas
de la note : “Français, musique, _et blanchissage_ — en supplément.” »

« Vous ne devez pas en avoir eu grand besoin, » dit Alice ; « puisque vous
viviez au fond de la mer. »

« Je n'avais pas les moyens de l'apprendre, » dit la Fausse-Tortue avec un
soupir. « Je n'ai suivi que le cours ordinaire. »

« Qu'est-ce que c'était ? » demanda Alice.

« Lier et S'écrier, bien entendu, pour commencer, » répondit la
Fausse-Tortue ; « et puis les différentes branches de l'Arithmétique —
l'Ambition, la Distraction, l'Enlaidification et la Dérision. »

« Je n'ai jamais entendu parler de l'“Enlaidification”, » se hasarda à dire
Alice. « Qu'est-ce que c'est ? »

Le Griffon leva ses deux pattes en signe de surprise. « Comment ! Jamais
entendu parler d'enlaidir ! » s'exclama-t-il. « Vous savez ce que c'est
qu'embellir, je suppose ? »

« Oui, » dit Alice d'un ton hésitant : « cela veut dire — rendre —
quelque chose — plus joli. »

« Eh bien, alors, » continua le Griffon, « si vous ne savez pas ce que c'est
qu'enlaidir, vous _êtes_ une nigaude. »

Alice ne se sentit pas encouragée à poser d'autres questions là-dessus,
aussi se tourna-t-elle vers la Fausse-Tortue et dit : « Qu'aviez-vous encore
à apprendre ? »

« Eh bien, il y avait la Mystoire, » répondit la Fausse-Tortue, comptant les
matières sur ses nageoires, « — la Mystoire, ancienne et moderne, avec la
Mérographie : et puis le Dessein — le maître de Dessein était un vieux
congre qui venait une fois par semaine : c'est _lui_ qui nous enseignait le
Dessein, l'Esquive et la Pâmoison à l'huile. »

« À quoi cela ressemblait-il ? » dit Alice.

« Eh bien, je ne peux pas vous le montrer moi-même, » dit la Fausse-Tortue :
« je suis trop raide. Et le Griffon ne l'a jamais appris. »

« Pas eu le temps, » dit le Griffon : « je suis allé chez le maître de
lettres classiques, cependant. C'était un vieux crabe, _voilà_ ce qu'il
était. »

« Je ne suis jamais allée chez lui, » dit la Fausse-Tortue avec un soupir :
« il enseignait le Lutin et le Grief, à ce qu'on disait. »

« C'est bien vrai, c'est bien vrai, » dit le Griffon, soupirant à son tour ;
et les deux créatures cachèrent leur visage dans leurs pattes.

« Et combien d'heures de cours faisiez-vous par jour ? » dit Alice, pressée
de changer de sujet.

« Dix heures le premier jour, » dit la Fausse-Tortue : « neuf le lendemain,
et ainsi de suite. »

« Quel plan curieux ! » s'exclama Alice.

« C'est la raison pour laquelle on les appelle des cours, » remarqua le
Griffon : « parce qu'ils sont plus courts de jour en jour. »

C'était là une idée toute nouvelle pour Alice, et elle y réfléchit un peu
avant de faire sa remarque suivante. « Alors le onzième jour devait être un
jour de congé ? »

« Bien sûr que oui, » dit la Fausse-Tortue.

« Et comment vous arrangiez-vous le douzième ? » poursuivit Alice avec
empressement.

« Assez parlé de cours, » interrompit le Griffon d'un ton très décidé :
« parlez-lui un peu des jeux, maintenant. »"""

glossary = {
    "the Mock Turtle": "la Fausse-Tortue",
    "the Duchess": "la Duchesse",
    "the Gryphon": "le Griffon",
}

chunk = json.load(open("chunk.json"))

missing = [k for k, v in glossary.items() if v not in translation]
if missing:
    raise SystemExit("glossary values missing from translation: %s" % missing)

result = {
    "chunk_id": chunk["id"],
    "glossary": glossary,
    "translation": translation,
}
with open("result.json", "w") as f:
    json.dump(result, f, ensure_ascii=False, indent=2)

src_paras = len([p for p in chunk["text"].split("\n\n") if p.strip()])
out_paras = len([p for p in translation.split("\n\n") if p.strip()])
print("chunk_id:", result["chunk_id"])
print("glossary terms:", len(glossary))
print("translation chars:", len(translation))
print("source paragraphs:", src_paras, "translated paragraphs:", out_paras)
