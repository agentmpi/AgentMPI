"""E5: one job, many machines.

Every earlier experiment runs its ranks on one host, because every earlier
transport needs a shared filesystem.  This one runs each rank in its own cloud
sandbox --- separate VM, separate kernel, no route between them --- with the git
device as the transport, and asks the only question that matters for the claim
that the waist is real: does the protocol above it notice?

Three subcommands, in the order a run uses them:

``create``   make the job on the shared branch and record the launch plan.  Run
             once, anywhere with push access.
``run``      be one rank.  Run once per machine.  Joins the job, allgathers an
             identity that only the machine itself can produce (its kernel boot
             id), passes a barrier, sums ranks with an in-journal allreduce, gathers
             a timing report to rank 0, and finalises.  Writes nothing the harness
             needs anywhere but the device, because the machine is gone afterwards.
``collect``  read the branch back and produce the evidence: which ranks ran on
             which machines, whether every collective closed, and what the
             transport cost in pushes and rejections.

The identity payload is the point of the design.  A host name is whatever the
launcher says it is; a kernel boot id is generated by the machine at boot and
cannot be shared by two of them, so ``n`` distinct boot ids in one allgather is
proof of ``n`` machines that no aggregate assembled afterwards could fake.
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import socket
import subprocess
import time
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
RUNS = HERE.parent.parent / "runs"


def identity(rank: int) -> dict[str, Any]:
    boot = Path("/proc/sys/kernel/random/boot_id")
    return {
        "rank": rank,
        "hostname": socket.gethostname(),
        "boot_id": boot.read_text().strip() if boot.exists() else None,
        "kernel": platform.release(),
        "pid": os.getpid(),
        "session": os.environ.get("CLAUDE_CODE_REMOTE_SESSION_ID"),
        "container": os.environ.get("CLAUDE_CODE_CONTAINER_ID"),
        "started_at": time.time(),
    }


def _env(a: argparse.Namespace) -> None:
    os.environ["AMPI_DEVICE"] = "git"
    if a.remote:
        os.environ["AMPI_GIT_REMOTE"] = a.remote
    os.environ["AMPI_GIT_BRANCH"] = a.branch or f"ampi-jobs/{a.name}"


def cmd_create(a: argparse.Namespace) -> dict[str, Any]:
    _env(a)
    from ampi.runtime import Ampi

    root = Path(a.root or RUNS / a.name / "job")
    job = Ampi.create(str(root), a.size, device="git", force=True,
                      join_deadline_s=a.join_deadline,
                      meta={"experiment": "e5_multihost", "remote": a.remote,
                            "branch": os.environ["AMPI_GIT_BRANCH"]})
    plan = {
        "name": a.name, "job": job.manifest.job_id, "size": a.size,
        "remote": a.remote, "branch": os.environ["AMPI_GIT_BRANCH"],
        "requested_ranks": list(range(a.size)),
        "created_at": time.time(), "created_on": identity(-1),
    }
    run_dir = RUNS / a.name
    run_dir.mkdir(parents=True, exist_ok=True)
    (run_dir / "launch_plan.json").write_text(json.dumps(plan, indent=2), encoding="utf-8")
    print(json.dumps(plan, indent=2))
    return plan


def cmd_run(a: argparse.Namespace) -> dict[str, Any]:
    _env(a)
    from ampi.runtime import Ampi

    root = Path(a.root or RUNS / a.name / "job")
    me = identity(a.rank)
    t: dict[str, float] = {}
    t0 = time.time()
    amp = Ampi(str(root), rank=a.rank, expect_rank=a.rank)
    amp.init(lease_s=a.lease)
    t["init_s"] = time.time() - t0

    t1 = time.time()
    hello = amp.allgather("hello", payload=me, materialize=True, timeout=a.timeout)
    t["allgather_s"] = time.time() - t1
    peers = {b["rank"]: b["body"] for b in hello.get("bodies", [])}

    t2 = time.time()
    amp.barrier("sync", timeout=a.timeout)
    t["barrier_s"] = time.time() - t2

    t3 = time.time()
    total = amp.allreduce("ranksum", payload=a.rank, op="sum", timeout=a.timeout)
    t["allreduce_s"] = time.time() - t3

    dev = amp.device.stats()
    report = {"rank": a.rank, "machine": me["boot_id"], "hostname": me["hostname"],
              "peers_seen": len(peers), "distinct_machines_seen":
              len({p.get("boot_id") for p in peers.values()}),
              "ranksum": total.get("value"), "timings": t,
              "pushes": dev["pushes"], "rejections": dev["rejections"], "fetches": dev["fetches"]}
    t4 = time.time()
    amp.gather("report", payload=report, root=0, materialize=True, timeout=a.timeout)
    t["gather_s"] = time.time() - t4
    amp.finalize(note="e5 done")
    report["timings"] = t
    report["wall_s"] = time.time() - t0
    # The machine this ran on is about to disappear; the device is the only
    # durable place, so the per-rank report goes into the trace.
    amp.trace("e5.report", rank=a.rank, report=report)
    print(json.dumps(report, indent=2))
    return report


def cmd_collect(a: argparse.Namespace) -> dict[str, Any]:
    _env(a)
    from ampi.device.gitlog import GitDevice

    run_dir = RUNS / a.name
    root = Path(a.root or run_dir / "job")
    dev = GitDevice(str(root))
    dev.initialize()
    state = dev._sync()
    ranks = {k.split("\t", 1)[1]: v[-1]["value"] for k, v in state["cells"].items()
             if k.startswith("rank\t")}
    events = state["streams"].get("event", [])
    reports = {e["rank"]: e.get("report") for e in events if e.get("kind") == "e5.report"}
    hellos = [r for r in state["streams"].get("coll", []) if r.get("label") == "hello"]
    machines: dict[int, str | None] = {}
    for rec in hellos:
        body = rec.get("body")
        if isinstance(body, dict):
            machines[rec["rank"]] = body.get("boot_id")
        elif rec.get("handle"):
            obj = state["obj"].get(rec["handle"])
            try:
                machines[rec["rank"]] = json.loads(obj).get("boot_id") if obj else None
            except (json.JSONDecodeError, AttributeError):
                machines[rec["rank"]] = None
    for r, rep in reports.items():
        machines.setdefault(r, rep.get("machine") if rep else None)
    colls: dict[str, dict[str, int]] = {}
    for rec in state["streams"].get("coll", []):
        colls.setdefault(rec["label"], {}).setdefault(rec.get("state") or "?", 0)
        colls[rec["label"]][rec.get("state") or "?"] += 1
    log = subprocess.run(["git", "rev-list", "--count", "HEAD"], cwd=str(root),
                         capture_output=True, text=True).stdout.strip()
    summary = {
        "name": a.name, "branch": dev.branch, "remote": dev._remote,
        "size": len(ranks),
        "rank_states": {r: v.get("state") for r, v in sorted(ranks.items(), key=lambda kv: int(kv[0]))},
        "machines": {str(r): m for r, m in sorted(machines.items())},
        "distinct_machines": len({m for m in machines.values() if m}),
        "collectives": colls,
        "reports": len(reports),
        "pushes_total": sum((rep or {}).get("pushes", 0) for rep in reports.values()),
        "rejections_total": sum((rep or {}).get("rejections", 0) for rep in reports.values()),
        "wall_s_by_rank": {str(r): round((rep or {}).get("wall_s", 0), 1)
                           for r, rep in sorted(reports.items())},
        "commits_on_branch": int(log or 0),
        "events": len(events),
    }
    evidence = run_dir / "evidence"
    evidence.mkdir(parents=True, exist_ok=True)
    (evidence / "state.json").write_text(json.dumps(state, indent=1), encoding="utf-8")
    (evidence / "git-log.txt").write_text(
        subprocess.run(["git", "log", "--format=%H %ct %s", "--reverse"], cwd=str(root),
                       capture_output=True, text=True).stdout, encoding="utf-8")
    (run_dir / "report.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(json.dumps(summary, indent=2))
    return summary


def main(argv: list[str] | None = None) -> Any:
    ap = argparse.ArgumentParser(description="E5: one AgentMPI job across many machines")
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("create", "run", "collect"):
        p = sub.add_parser(name)
        p.add_argument("--name", required=True)
        p.add_argument("--remote", default=None, help="git remote URL; omit for a local bare repo")
        p.add_argument("--branch", default=None, help="default ampi-jobs/<name>")
        p.add_argument("--root", default=None, help="local working tree; default runs/<name>/job")
    sub.choices["create"].add_argument("--size", type=int, required=True)
    sub.choices["create"].add_argument("--join-deadline", type=float, default=3600.0,
                                       help="seconds ranks have to arrive; machines boot slowly")
    sub.choices["run"].add_argument("--rank", type=int, required=True)
    sub.choices["run"].add_argument("--timeout", type=float, default=1800.0)
    sub.choices["run"].add_argument("--lease", type=float, default=3600.0)
    a = ap.parse_args(argv)
    return {"create": cmd_create, "run": cmd_run, "collect": cmd_collect}[a.cmd](a)


if __name__ == "__main__":
    main()
